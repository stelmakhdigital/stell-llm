// NGRAM-драфтер (ADR-13 [R5], round 11): драфтер-плагин для
// SpeculativeDecoder БЕЗ второй модели — статистика n-грамм по контексту.
//
// Контракт DrafterFn (spec_decode.hpp): полный контекст (промпт + испущенные
// токены) → до n_draft кандидатов, детерминированно. Кандидаты верифицируются
// целью (FP32-логиты) — качество побитово == plain greedy независимо от
// качества драфтера; n-граммный драфтер влияет только на долю принятых
// (accept-rate), решает арбитр-калибровка (PLAN.md §2.4).
//
// Модель данных:
//   * текст — подтверждённые токены (контекст, передаваемый декодером;
//     испущенные декодером токены попадают в текст при следующем вызове —
//     они уже часть контекста). Драфт-кандидаты НЕ индексируются (они не
//     подтверждены — индекс честен).
//   * индекс: окно длины ≤ max_order (хвостовое), ключ — FNV-1a хеш окна,
//     значение — позиции i в тексте, где окно текста[i-L+1..i] совпадает;
//     прогноз для совпавшего окна — СЛЕДУЮЩИЙ токен текста (text_[i+1]),
//     берём самую свежую позицию (детерминизм: последняя).
//
// Драфт: жадное продолжение — суффикс контекста длины L (от max_order вниз
// до 1) ищется в индексе; найден — кандидата испускаем и повторяем для
// расширенного суффикса (суффиксы, захватывающие недрафтованные кандидаты,
// в индексе отсутствуют — честный фолбэк на короткое L). Нет совпадения —
// пустой остаток (декодер дорисует plain greedy — корректно по контракту).
//
// ЧЕСТНЫЕ ОГРАНИЧЕНИЯ: n-граммный драфтер полезен на повторяющемся/
// локально-детерминированном тексте; на «свежем» тексте даёт пустые драфты
// (rounds деградируют к plain greedy — телеметрия честная, арбитр решает).
// Индекс строится инкрементально (контекст декодера растёт монотонно);
// при не-монотонном контексте — полная перестройка (корректность важнее
// скорости; это не горячий путь CUDA-контура).
#pragma once

#include <cstddef>
#include <cstdint>
#include <functional>
#include <unordered_map>
#include <vector>

#include "stell/engine/spec_decode.hpp"

namespace stell::engine {

class NgramDrafter {
public:
    // max_order — максимальная длина суффикс-окна (порядок n-грамм);
    // max_context — предел индексируемого текста (честное окно: старые
    // токены выпадают — индекс не растёт неограниченно).
    explicit NgramDrafter(std::size_t max_order = 8,
                          std::size_t max_context = 65536);

    // Плагин для SpeculativeDecoder (DrafterFn).
    SpeculativeDecoder::DrafterFn fn();

    // Для тестов/телеметрии: размер индексированного текста.
    std::size_t indexed_tokens() const { return text_.size(); }

private:
    void ensure_indexed(const std::vector<std::int32_t>& context);
    void append_token(std::int32_t token);

    std::size_t max_order_;
    std::size_t max_context_;
    std::vector<std::int32_t> text_;
    // ключ → позиции i (окно длины L заканчивается в i; прогноз — text_[i+1])
    std::unordered_map<std::uint64_t, std::vector<std::uint32_t>> index_;
};

} // namespace stell::engine
